# -*- coding: utf-8 -*-
"""专有名词纠错表（共享模块）。
visit_pipeline.py append前自动应用，fix_typos.py批量订正也用这个。
新增纠错只需在这里加一行，所有流程自动生效。
"""
# 错误写法 -> 正确写法（长的放前面，避免短词先替换破坏长词）
CORRECTIONS = [
    # 人名
    ("吴光彪", "吴光标"), ("五官标", "吴光标"),
    ("郑天池", "郑天慈"), ("郑天赐", "郑天慈"),
    ("梁家俊", "梁佳俊"),
    ("尤连胜", "尤连生"), ("全航行", "尤连生"),
    ("赵本成", "赵本存"),
    ("崔长健", "崔长见"),
    ("刘葛伟", "刘革伟"),
    ("陈德生", "陈德胜"),
    ("王名营", "王明营"),
    ("王维左", "王为左"),
    ("刘洪阳", "刘宏阳"),
    ("胡一军", "胡义军"),
    ("魏忠柱", "魏中住"),
    ("何宏源", "何鸿源"), ("何红颜", "何鸿源"), ("卢洪源", "何鸿源"),
    ("吴香平", "吴湘平"),
    # 公司/品牌
    ("百盛", "百胜"),
    ("君和兴", "均合兴"), ("君和鑫", "均合兴"),
    ("海帝", "海的"),
    ("陈奥", "城澳"),
    ("威沙", "威鲨"),
    ("京东方精工", "广东东方精工科技股份有限公司"),
    ("军心", "珠海军心"), ("军鑫", "珠海军心"),
    ("苍龙", "长隆"),
    # 高风险词暂不自动替换（需人工确认）：王源、于心、水下部分
]

def apply_corrections(text):
    """应用纠错表到文本，返回(修正后文本, 修改列表)"""
    changes = []
    for wrong, right in CORRECTIONS:
        if wrong == right:
            continue
        if wrong in text:
            cnt = text.count(wrong)
            text = text.replace(wrong, right)
            changes.append(f"{wrong}->{right} x{cnt}")
    return text, changes
